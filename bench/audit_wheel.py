"""Validate wheel RECORD, exclude build debris, optionally compare installed bytes.

This is an archive integrity check, not a platform ABI or license-completeness
audit. Generated bytecode must not be shipped even when Python can regenerate it.
"""

import argparse
import base64
import csv
import hashlib
import io
import json
from pathlib import Path, PurePosixPath
from zipfile import ZipFile


def audit(wheel, installed_root=None):
    errors = []
    with ZipFile(wheel) as archive:
        names = [name for name in archive.namelist() if not name.endswith("/")]
        assert len(names) == len(set(names)), "duplicate archive paths"
        for name in names:
            path = PurePosixPath(name)
            assert not path.is_absolute() and ".." not in path.parts, f"unsafe archive path: {name}"
        records = [n for n in names if n.endswith(".dist-info/RECORD")]
        assert len(records) == 1, "expected one distribution RECORD"
        rows = list(csv.reader(io.StringIO(archive.read(records[0]).decode())))
        assert len(rows) == len({r[0] for r in rows}), "duplicate RECORD paths"
        assert {r[0] for r in rows} == set(names), "RECORD must cover every archive member"
        files = {}
        for name, checksum, size in rows:
            content = archive.read(name)
            sha = hashlib.sha256(content).hexdigest()
            files[name] = {"sha256": sha, "bytes": len(content)}
            if name == records[0]:
                assert not checksum and not size
            else:
                algorithm, encoded = checksum.split("=", 1)
                assert algorithm == "sha256", f"unsupported RECORD digest: {algorithm}"
                assert base64.urlsafe_b64encode(bytes.fromhex(sha)).rstrip(b"=").decode() == encoded, name
                assert int(size) == len(content), name
            if "__pycache__" in PurePosixPath(name).parts or name.endswith((".pyc", ".pyo")):
                errors.append(f"generated Python bytecode: {name}")
            elif installed_root is not None and ".dist-info/" not in name:
                installed = installed_root / name
                if not installed.is_file() or hashlib.sha256(installed.read_bytes()).hexdigest() != sha:
                    errors.append(f"installed source/native bytes differ: {name}")
    return {
        "scope": "wheel RECORD integrity, generated bytecode exclusion, optional installed source/native bytes; no ABI or complete license audit",
        "wheel": str(wheel.resolve()),
        "wheel_sha256": hashlib.sha256(wheel.read_bytes()).hexdigest(),
        "script_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        "installed_root": str(installed_root) if installed_root else None,
        "record_valid": True,
        "clean": not errors,
        "errors": errors,
        "files": files,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--wheel", type=Path, required=True)
    parser.add_argument("--installed-root", type=Path)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    assert not args.out.exists(), "retain previous audit reports"
    result = audit(args.wheel, args.installed_root)
    args.out.write_text(json.dumps(result, indent=2) + "\n")
    print(json.dumps({k: v for k, v in result.items() if k != "files"}, indent=2))
    raise SystemExit(0 if result["clean"] else 1)


if __name__ == "__main__":
    main()
